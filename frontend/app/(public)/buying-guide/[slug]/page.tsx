function ArticleSchemas({
  article,
  faqs,
  slug,
}: {
  article: Article;
  faqs: ArticleFaq[];
  slug: string;
}) {
  return (
    <>
      <JsonLd
        id={`article-${slug}`}
        data={articleSchema({
          headline: article.title,
          description: article.metaDescription,
          slug,
          datePublished: article.publishedAt?.toISOString(),
          dateModified: article.updatedAt?.toISOString(),
        })}
      />
      {faqs.length > 0 && <JsonLd id={`article-faq-${slug}`} data={faqSchema(faqs)} />}
      <JsonLd
        id={`article-breadcrumb-${slug}`}
        data={breadcrumbSchema([
          { name: "Buying Guide", path: "/buying-guide" },
          { name: article.h1, path: `/buying-guide/${slug}` },
        ])}
      />
    </>
  );
}
