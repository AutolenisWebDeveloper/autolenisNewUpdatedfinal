// Phase C1 — programmatic buying-guide article route. Serves any PUBLISHED
// ContentArticle generated by the Phase C2 engine. The six cornerstone pillar
// pages live at their own static routes and take precedence over this dynamic
// segment, so this only ever resolves programmatic slugs.
//
// ISR keeps DB reads off the hot path while still picking up newly published
// articles within the revalidation window.
export const revalidate = 3600;

const CALCULATOR_URL = "/tools/dealer-fee-calculator";

interface PageProps {
  params: Promise<{ slug: string }>;
}

interface ArticleFaq {
  question: string;
  answer: string;
}

type Article = NonNullable<Awaited<ReturnType<typeof loadArticle>>>;

async function loadArticle(slug: string) {
  try {
    return await prisma.contentArticle.findFirst({
      where: { slug, status: "PUBLISHED" },
    });
  } catch {
    // DB unavailable (e.g. at build time) — treat as not found.
    return null;
  }
}

function parseFaqs(faqJson: string | null): ArticleFaq[] {
  if (!faqJson) return [];
  try {
    const parsed = JSON.parse(faqJson);
    if (!Array.isArray(parsed)) return [];
    return parsed
      .filter(
        (f): f is ArticleFaq =>
          typeof f?.question === "string" && typeof f?.answer === "string",
      )
      .map((f) => ({ question: f.question, answer: f.answer }));
  } catch {
    return [];
  }
}

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { slug } = await params;
  const article = await loadArticle(slug);
  if (!article) {
    return { title: "Article not found | AutoLenis", robots: { index: false, follow: false } };
  }
  return buildPageMetadata({
    title: article.title,
    description: article.metaDescription,
    path: `/buying-guide/${slug}`,
  });
}

