export const metadata: Metadata = { title: "Prequalification" };

import { requireBuyer } from "@/lib/auth/session";
import { redirect } from "next/navigation";
import PrequalFormClient from "@/components/buyer/PrequalFormClient";
import PrequalBudgetCalculator from "@/components/buyer/PrequalBudgetCalculator";
import { formatCents } from "@/lib/utils";
import {
  getStabilityFactor,
  FRONT_END_AUTO_DTI,
  BACK_END_TOTAL_DTI,
} from "@/lib/services/prequal/income-gate";
import {
  CheckCircle2,
  Clock,
  ArrowRight,
  RefreshCw,
  ShieldCheck,
  ChevronDown,
  ChevronRight,
  Star,
  CalendarDays,
  Info,
  AlertCircle,
  Sparkles,
  TrendingUp,
  Search,
  ListChecks,
  BadgeCheck,
  Banknote,
  Calculator,
  Car,
  FileText,
  Pen,
  Package,
} from "lucide-react";
